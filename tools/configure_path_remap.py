"""Generate local Cargo path remapping without committing machine-specific paths."""

import json
import os
import subprocess
import tempfile
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / ".cargo" / "path-remap.toml"


def output(*args, cwd=ROOT):
    return subprocess.check_output(args, cwd=cwd, encoding="utf-8").strip()


def configure():
    # Discover dependency roots before loading the generated (required) include.
    # --manifest-path alone does not load the project's .cargo/config.toml.
    with tempfile.TemporaryDirectory(prefix="edot-remap-") as temporary:
        metadata = json.loads(
            output(
                "cargo",
                "metadata",
                "--locked",
                "--format-version",
                "1",
                "--manifest-path",
                str(ROOT / "Cargo.toml"),
                "--filter-platform",
                "x86_64-pc-windows-msvc",
                cwd=temporary,
            )
        )
    prefixes = {}

    def add(path, replacement):
        value = str(path).rstrip("/\\")
        # rustc remapping is textual: cover native and forward slash forms.
        for variant in {value, value.replace("\\", "/"), value.replace("/", "\\")}:
            prefixes[variant] = replacement

    add(ROOT, "edot")
    add(metadata["target_directory"], "build")
    git_packages = {}
    for package in metadata["packages"]:
        directory = Path(package["manifest_path"]).parent
        source = package["source"] or ""
        if source.startswith("registry+"):
            add(directory.parent, "crates")
        elif source.startswith("git+"):
            git_packages.setdefault(source, []).append(directory)
        elif directory != ROOT:
            add(directory, package["name"])

    # A workspace fork can contain many packages. Map their common directory
    # once to avoid repeating a long compiler flag for every workspace member.
    for source, directories in git_packages.items():
        repository = Path(urlparse(source.removeprefix("git+")).path).name
        add(os.path.commonpath(directories), repository.removesuffix(".git"))

    sysroot = output("rustc", "--print", "sysroot")
    add(sysroot, "rust")
    # Distributed std metadata also uses this mixed-separator spelling.
    for suffix in ["/lib/rustlib/src/rust", "\\lib/rustlib/src/rust"]:
        add(sysroot + suffix, "rust")

    flags = ["--remap-path-scope=object"]
    # Last matching prefix wins, so more specific paths must come last.
    flags.extend(
        f"--remap-path-prefix={source}={target}"
        for source, target in sorted(
            prefixes.items(), key=lambda item: (len(item[0]), item[0])
        )
    )
    text = (
        "# Generated by python tools/configure_path_remap.py; do not commit.\n"
        "# Regenerate after moving the checkout, Cargo cache, or Rust toolchain,\n"
        "# and after changing dependency versions / Git revisions.\n"
        "[target.x86_64-pc-windows-msvc]\n"
        "rustflags = [\n"
        + "".join(f"    {json.dumps(flag)},\n" for flag in flags)
        + "]\n"
    )
    if not CONFIG.exists() or CONFIG.read_text(encoding="utf-8") != text:
        pending = CONFIG.with_suffix(".toml.tmp")
        pending.write_text(text, encoding="utf-8")
        pending.replace(CONFIG)
    print(f"Configured {len(prefixes)} path prefixes in {CONFIG}")


if __name__ == "__main__":
    configure()
